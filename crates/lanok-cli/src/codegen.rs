// Shared

/// `type` may be a string or an array (schemars emits `["string", "null"]` for
/// an Option). Take the first non-null entry: the nullability is carried by the
/// field being optional.
fn type_name(schema: &Value) -> Option<&str> {
    match schema.get("type")? {
        Value::String(name) => Some(name),
        Value::Array(names) => names
            .iter()
            .filter_map(Value::as_str)
            .find(|n| *n != "null")
            .or(Some("null")),
        _ => None,
    }
}

fn union(options: &Value, render: fn(&Value) -> String, join: &str, fallback: &str) -> String {
    let rendered: Vec<String> = options
        .as_array()
        .map(|options| options.iter().map(render).collect())
        .unwrap_or_default();
    if rendered.is_empty() {
        return fallback.to_string();
    }
    rendered.join(join)
}

/// `tool_call` becomes `toolCall`, which is what a TypeScript reader expects.
fn camel(input: &str) -> String {
    let mut out = String::new();
    let mut capitalize = false;
    for c in input.chars() {
        if c == '_' || c == '-' || c == '/' {
            capitalize = true;
        } else if capitalize {
            out.extend(c.to_uppercase());
            capitalize = false;
        } else {
            out.push(c);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    #[test]
    fn optional_fields_are_optional_in_both_languages() {
        let schema = json!({
            "properties": { "text": { "type": "string" }, "shout": { "type": "boolean" } },
            "required": ["text"]
        });
        let python = python_type("EchoParams", &schema);
        assert!(python.contains("text: str"));
        assert!(python.contains("shout: NotRequired[bool]"));

        let typescript = typescript_type("EchoParams", &schema);
        assert!(typescript.contains("text: string;"));
        assert!(typescript.contains("shout?: boolean;"));
    }

    #[test]
    fn an_option_renders_as_the_inner_type() {
        // schemars emits ["string", "null"] for Option<String>; the nullability
        // is already carried by the field being absent from `required`.
        let schema = json!({ "type": ["string", "null"] });
        assert_eq!(python_scalar(&schema), "str");
        assert_eq!(typescript_scalar(&schema), "string");
    }

    #[test]
    fn references_become_named_types() {
        let schema = json!({ "$ref": "#/$defs/AskResult" });
        assert_eq!(python_scalar(&schema), "AskResult");
        assert_eq!(typescript_scalar(&schema), "AskResult");
    }

    #[test]
    fn arrays_and_enums_keep_their_shape() {
        let array = json!({ "type": "array", "items": { "type": "integer" } });
        assert_eq!(python_scalar(&array), "list[int]");
        assert_eq!(typescript_scalar(&array), "Array<number>");

        let choice = json!({ "type": "string", "enum": ["yes", "no"] });
        assert_eq!(python_scalar(&choice), r#"Literal["yes", "no"]"#);
        assert_eq!(typescript_scalar(&choice), r#""yes" | "no""#);
    }

    #[test]
    fn an_unknown_shape_degrades_instead_of_failing() {
        // Precision is lost, the SDK still builds. A protocol with an exotic
        // payload should not be ungeneratable.
        let exotic = json!({ "not": { "type": "string" } });
        assert_eq!(python_scalar(&exotic), "Any");
        assert_eq!(typescript_scalar(&exotic), "unknown");
    }

    #[test]
    fn wire_names_become_idiomatic_identifiers() {
        assert_eq!(camel("tool_call"), "toolCall");
        assert_eq!(camel("ui_ask"), "uiAsk");
        assert_eq!(camel("echo"), "echo");
    }
}
